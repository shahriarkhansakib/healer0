/**
 * Returns the Bangla translation for a clinical assessment question.
 * Falls back to matching by question code, English text, or the original text.
 */
export function getQuestionBanglaText(
  englishText: string,
  questionCode?: string | null
): string {
  if (questionCode && BANGLA_QUESTION_TRANSLATIONS[questionCode]) {
    return BANGLA_QUESTION_TRANSLATIONS[questionCode];
  }

  // Try matching directly by English text
  for (const [code, bn] of Object.entries(BANGLA_QUESTION_TRANSLATIONS)) {
    // If the question code is embedded in text
    if (code === questionCode) return bn;
  }

  return englishText;
}

/**
 * Returns the Bangla translation for an option label.
 */
export function getOptionBanglaLabel(englishLabel: string): string {
  const trimmed = englishLabel.trim();
  if (BANGLA_OPTION_TRANSLATIONS[trimmed]) {
    return BANGLA_OPTION_TRANSLATIONS[trimmed];
  }

  // Case-insensitive lookup fallback
  const lower = trimmed.toLowerCase();
  for (const [en, bn] of Object.entries(BANGLA_OPTION_TRANSLATIONS)) {
    if (en.toLowerCase() === lower) {
      return bn;
    }
  }

  return englishLabel;
}

/**
 * Returns the Bangla translation for recall timeframe.
 */
export function getTimeframeBangla(timeframe?: string | null): string {
  if (!timeframe) return "সাধারণত";
  const clean = timeframe.trim().toLowerCase();
  return BANGLA_TIMEFRAME_TRANSLATIONS[clean] || timeframe.replace(/_/g, " ");
}
